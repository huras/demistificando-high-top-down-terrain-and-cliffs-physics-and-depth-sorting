const PADRAO_ARVORE = 0.12;

/** Fração a partir da base. Sem sprite, árvore usa broadleaf e mata usa green. */
export function fracaoBaseDoProp(prop) {
  const id = prop?.sprite;
  if (id && Object.prototype.hasOwnProperty.call(PIVO_BASE, id)) return PIVO_BASE[id];
  const tipo = prop?.tipo || prop?.classe;
  if (tipo === "arvore") return PIVO_BASE.broadleaf ?? PADRAO_ARVORE;
  if (tipo === "mata" || tipo === "grama") return PIVO_BASE.green ?? 0;
  return 0;
}

export function fracaoBaseDe(id, classe) {
  return fracaoBaseDoProp({ sprite: id, tipo: classe });
}
